import { describe, expect, it } from "vitest";

import { datesBetween } from "./selection";

describe("datesBetween", () => {
  it("同一天只返回一个日期", () => {
    expect(datesBetween("2026-10-27", "2026-10-27")).toEqual(["2026-10-27"]);
  });

  it("返回正向连续日期", () => {
    expect(datesBetween("2026-10-27", "2026-10-30")).toEqual([
      "2026-10-27",
      "2026-10-28",
      "2026-10-29",
      "2026-10-30",
    ]);
  });

  it("起止顺序反过来也能工作", () => {
    expect(datesBetween("2026-10-30", "2026-10-27")).toEqual([
      "2026-10-27",
      "2026-10-28",
      "2026-10-29",
      "2026-10-30",
    ]);
  });

  it("可以跨月、跨年", () => {
    expect(datesBetween("2026-12-30", "2027-01-02")).toEqual([
      "2026-12-30",
      "2026-12-31",
      "2027-01-01",
      "2027-01-02",
    ]);
  });

  it("包含闰日", () => {
    expect(datesBetween("2028-02-28", "2028-03-01")).toEqual([
      "2028-02-28",
      "2028-02-29",
      "2028-03-01",
    ]);
  });
});
